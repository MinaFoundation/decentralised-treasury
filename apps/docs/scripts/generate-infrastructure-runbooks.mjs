const GENERATED_MARKER =
  "<!-- Generated by scripts/generate-infrastructure-runbooks.mjs. Do not edit this page. -->";

function normalizeNewlines(value) {
  return value.replaceAll("\r\n", "\n");
}

function displayTransform(value) {
  return normalizeNewlines(value)
    .replace(/<(https?:\/\/[^>\s]+)>/g, "[$1]($1)");
}

async function companionYamlFiles(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  return entries
    .filter((entry) => entry.isFile() && /\.ya?ml$/i.test(entry.name))
    .map((entry) => path.join(directory, entry.name))
    .sort((left, right) => left.localeCompare(right));
}

async function listFilesRecursively(directory) {
  const files = [];
  let entries;
  try {
    entries = await readdir(directory, { withFileTypes: true });
  } catch (error) {
    if (error.code === "ENOENT") return files;
    throw error;
  }
  entries.sort((left, right) => left.name.localeCompare(right.name));
  for (const entry of entries) {
    const file = path.join(directory, entry.name);
    if (entry.isDirectory()) files.push(...(await listFilesRecursively(file)));
    else if (entry.isFile()) files.push(file);
  }
  return files;
}

function sourceEntry(file, bytes) {
  return `- \`${relativeToRepository(file)}\` (SHA-256: \`${sha256(bytes)}\`)`;
}

async function renderRunbook(record) {
  const directory = path.join(sourceRoot, record.sourceDirectory);
  const readmeFile = path.join(directory, "README.md");
  const readmeBytes = await readFile(readmeFile);
  const yamlFiles = await companionYamlFiles(directory);
  const yamlSources = await Promise.all(
    yamlFiles.map(async (file) => {
      const relativeSourcePath = path
        .relative(sourceRoot, file)
        .split(path.sep)
        .join("/");
      return {
        file,
        bytes: await readFile(file),
        downloadPath: `/runbook-files/${relativeSourcePath}`,
        staticPath: path.join(staticOutputRoot, relativeSourcePath),
      };
    }),
  );

  const page = [
    "---",
    `title: "${record.id} — ${record.title}"`,
    `sidebar_label: "${record.id} — ${record.title}"`,
    "audience: operator",
    "page_kind: procedure",
    "---",
    "",
    GENERATED_MARKER,
    "",
    ":::info Source-controlled procedure",
    "",
    `This page contains the complete \`${relativeToRepository(readmeFile)}\` procedure and each YAML file in the same directory. Change the source files. Then run \`pnpm --dir apps/docs run generate:runbooks\`.`,
    "",
    ":::",
    "",
    displayTransform(readmeBytes.toString("utf8")).replace(/\n*$/, ""),
  ];

  for (const source of yamlSources) {
    page.push(
      "",
      `## Configuration File: \`${path.basename(source.file)}\``,
      "",
      `This is the complete \`${relativeToRepository(source.file)}\` file.`,
      "",
      `[Download \`${path.basename(source.file)}\`](pathname://${source.downloadPath})`,
      "",
      "```yaml",
      normalizeNewlines(source.bytes.toString("utf8")).replace(/\n*$/, ""),
      "```",
    );
  }

  page.push(
    "",
    "## Sources",
    "",
    sourceEntry(readmeFile, readmeBytes),
    ...yamlSources.map((source) => sourceEntry(source.file, source.bytes)),
  );

  return {
    page: {
      path: path.join(outputRoot, record.outputFile),
      content: `${page.join("\n")}\n`,
    },
    staticFiles: yamlSources.map((source) => ({
      path: source.staticPath,
      content: source.bytes,
    })),
  };
}

export async function expectedInfrastructureRunbooks() {
  const errors = [];
  const sourceFiles = new Set();
  try {
    for (const file of await listFilesRecursively(sourceRoot)) {
      sourceFiles.add(path.resolve(file));
    }
  } catch (error) {
    addError(
      errors,
      "devops/runbooks",
      `Cannot read the source library: ${error.message}`,
    );
  }

  const allowedSourceFiles = new Set([path.resolve(sourceRoot, "README.md")]);
  for (const record of RUNBOOKS) {
    const directory = path.join(sourceRoot, record.sourceDirectory);
    allowedSourceFiles.add(path.resolve(directory, "README.md"));
    try {
      for (const file of await companionYamlFiles(directory)) {
        allowedSourceFiles.add(path.resolve(file));
      }
    } catch (error) {
      if (error.code !== "ENOENT") throw error;
    }
  }

  for (const file of allowedSourceFiles) {
    if (!sourceFiles.has(file)) {
      addError(
        errors,
        relativeToRepository(file),
        "The registered runbook source does not exist.",
      );
    }
  }
  for (const file of sourceFiles) {
    if (!allowedSourceFiles.has(file)) {
      addError(
        errors,
        relativeToRepository(file),
        "The runbook generator does not account for this source file.",
      );
    }
  }

  const pages = [];
  const staticFiles = [];
  if (errors.length === 0) {
    for (const record of RUNBOOKS) {
      const rendered = await renderRunbook(record);
      pages.push(rendered.page);
      staticFiles.push(...rendered.staticFiles);
    }
  }
  return { errors, pages, staticFiles };
}

export async function checkInfrastructureRunbooks(expected) {
  const errors = [];
  const expectedFiles = new Set(
    expected.pages.map((page) => path.resolve(page.path)),
  );

  for (const page of expected.pages) {
    let actual;
    try {
      actual = await readFile(page.path, "utf8");
    } catch (error) {
      if (error.code === "ENOENT") {
        addError(
          errors,
          relativeToRepository(page.path),
          "The generated runbook page is missing. Run pnpm --dir apps/docs run generate:runbooks.",
        );
        continue;
      }
      throw error;
    }
    if (actual !== page.content) {
      addError(
        errors,
        relativeToRepository(page.path),
        "The generated runbook page is stale. Run pnpm --dir apps/docs run generate:runbooks.",
      );
    }
  }

  try {
    const entries = await readdir(outputRoot, { withFileTypes: true });
    for (const entry of entries) {
      if (
        !entry.isFile() ||
        !entry.name.endsWith(".md") ||
        entry.name === "index.md"
      ) {
        continue;
      }
      const file = path.resolve(outputRoot, entry.name);
      if (expectedFiles.has(file)) continue;
      const text = await readFile(file, "utf8");
      if (text.includes(GENERATED_MARKER)) {
        addError(
          errors,
          relativeToRepository(file),
          "This generated runbook page is not registered.",
        );
      }
    }
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
  }

  const expectedStaticFiles = new Set(
    expected.staticFiles.map((file) => path.resolve(file.path)),
  );
  for (const file of expected.staticFiles) {
    let actual;
    try {
      actual = await readFile(file.path);
    } catch (error) {
      if (error.code === "ENOENT") {
        addError(
          errors,
          relativeToRepository(file.path),
          "The runbook download is missing. Run pnpm --dir apps/docs run generate:runbooks.",
        );
        continue;
      }
      throw error;
    }
    if (!actual.equals(file.content)) {
      addError(
        errors,
        relativeToRepository(file.path),
        "The runbook download is stale. Run pnpm --dir apps/docs run generate:runbooks.",
      );
    }
  }

  for (const file of await listFilesRecursively(staticOutputRoot)) {
    if (!expectedStaticFiles.has(path.resolve(file))) {
      addError(
        errors,
        relativeToRepository(file),
        "This runbook download is not registered.",
      );
    }
  }

  return errors;
}

async function generate() {
  const expected = await expectedInfrastructureRunbooks();
  printErrors(expected.errors);
  if (expected.errors.length > 0) {
    process.exitCode = 1;
    return;
  }

  if (process.argv.includes("--check")) {
    const errors = await checkInfrastructureRunbooks(expected);
    printErrors(errors);
    if (errors.length > 0) process.exitCode = 1;
    else
      process.stdout.write(
        "The generated infrastructure runbooks are current.\n",
      );
    return;
  }

  await mkdir(outputRoot, { recursive: true });
  for (const page of expected.pages) await writeFile(page.path, page.content);
  for (const file of expected.staticFiles) {
    await mkdir(path.dirname(file.path), { recursive: true });
    await writeFile(file.path, file.content);
  }
  process.stdout.write(
    `Generated ${expected.pages.length} infrastructure runbook page(s) and ${expected.staticFiles.length} YAML download(s).\n`,
  );
}

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(process.argv[1]).href
) {
  await generate();
}
